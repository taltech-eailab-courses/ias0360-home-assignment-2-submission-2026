"""Export trained models and preprocessing constants into the Pico firmware.

Generates in firmware/gesture_inference/:
  src/preprocessing_settings.hpp   window/frame sizes, normalization, axis map, class names
  models/<name>_model_data.cpp     uint8 .tflite model as a C array
  models/model_registry.cpp        list of compiled-in models (best first)
  models/own_test_split.cpp        own recordings held out from training

By default exports the most accurate model of each architecture.
Choose explicitly with --models name1,name2.

Usage:  python training/export_firmware.py [--models initial,combined_best]
"""

from __future__ import annotations

import argparse
import json

import gesture_data as gd
from run_experiments import JSONL_PATH, MODELS_DIR, load_rows

FIRMWARE_DIR = gd.REPO_ROOT / "firmware" / "gesture_inference"
SETTINGS_PATH = FIRMWARE_DIR / "src" / "preprocessing_settings.hpp"
MODELS_OUT = FIRMWARE_DIR / "models"


def score(row):
    """Own-data accuracy, then validation accuracy."""
    own = row["own_acc_uint8"] if row["own_acc_uint8"] is not None else -1
    return (own, row["val_acc_mean"], -row["val_acc_std"])


def pick_default(rows):
    best_per_arch = {}
    for row in rows.values():
        # Only full runs trained with own recordings.
        if row.get("quick") or not row.get("own_in_training", True):
            continue
        arch = row["arch"]
        if arch not in best_per_arch or score(row) > score(best_per_arch[arch]):
            best_per_arch[arch] = row
    return sorted(best_per_arch.values(), key=score, reverse=True)


def c_array(name: str, data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 12):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",")
    return (f"// GENERATED by training/export_firmware.py - do not edit.\n"
            f"#include <cstdint>\n\n"
            f"alignas(16) extern const unsigned char {name}[] = {{\n" + "\n".join(lines) +
            f"\n}};\nextern const unsigned int {name}_len = {len(data)};\n")


def write_settings(normalizer, axis_map):
    index, sign = gd.parse_axis_map(axis_map)
    mean = ", ".join(f"{v:.9g}f" for v in normalizer["mean"])
    std = ", ".join(f"{v:.9g}f" for v in normalizer["std"])
    names = ", ".join(f'"{n}"' for n in gd.CLASS_NAMES)
    SETTINGS_PATH.write_text(f"""// GENERATED by training/export_firmware.py - do not edit.
#ifndef PREPROCESSING_SETTINGS_HPP
#define PREPROCESSING_SETTINGS_HPP

#include <cstdint>

constexpr int kNumAxes = {gd.NUM_AXES};
// Raw samples per axis (shorter recordings are padded, longer ones cut).
constexpr int kInputWindowLength = {gd.WINDOW_LENGTH};
// Frames per axis fed to the model.
constexpr int kTargetLength = {gd.TARGET_LENGTH};
constexpr int kPaddingModeWindow = {gd.PAD_MODE_WINDOW};
constexpr float kCountsPerG = {gd.COUNTS_PER_G:.1f}f;

// Axis map {tuple(axis_map)}:
// model axis i = kAxisSign[i] * recorded axis kAxisSource[i].
constexpr int kAxisSource[kNumAxes] = {{{", ".join(str(i) for i in index)}}};
constexpr int32_t kAxisSign[kNumAxes] = {{{", ".join(str(s) for s in sign)}}};

// Per-axis normalization (g - mean) / std.
constexpr float kAxisMean[kNumAxes] = {{{mean}}};
constexpr float kAxisStd[kNumAxes] = {{{std}}};

constexpr int kClassCount = {len(gd.CLASS_NAMES)};
constexpr const char* kClassNames[kClassCount] = {{{names}}};

#endif  // PREPROCESSING_SETTINGS_HPP
""")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--models", help="comma-separated experiment names (first = primary model)")
    args = parser.parse_args()

    rows = load_rows()
    if not rows:
        raise SystemExit(f"no results in {JSONL_PATH}; run training/run_experiments.py first")
    if args.models:
        missing = [n for n in args.models.split(",") if n not in rows]
        if missing:
            raise SystemExit(f"not trained yet: {missing}")
        chosen = [rows[n] for n in args.models.split(",")]
    else:
        chosen = pick_default(rows)

    normalizers = {json.dumps(r["normalizer"]) for r in chosen}
    if len(normalizers) != 1:
        raise SystemExit("chosen models were trained with different normalization statistics")
    axis_map = gd.load_axis_map()
    write_settings(chosen[0]["normalizer"], axis_map)

    for old in MODELS_OUT.glob("*_model_data.cpp"):
        old.unlink()
    entries = []
    for row in chosen:
        symbol = "model_" + "".join(c if c.isalnum() else "_" for c in row["name"])
        data = (MODELS_DIR / f"{row['name']}.tflite").read_bytes()
        (MODELS_OUT / f"{symbol}_model_data.cpp").write_text(c_array(symbol, data))
        description = row["description"].replace('"', "'")
        entries.append((symbol, row["name"], description, len(data)))
        own = "n/a" if row["own_acc_uint8"] is None else "%.1f %%" % (100 * row["own_acc_uint8"])
        print(f"exported {row['name']:<22} {len(data):6d} bytes  val {100 * row['val_acc_mean']:.1f} %  own {own}")

    externs = "\n".join(f"extern const unsigned char {s}[];" for s, *_ in entries)
    table = "\n".join(f'    {{"{n}", "{d}", {s}, {size}u}},' for s, n, d, size in entries)
    (MODELS_OUT / "model_registry.cpp").write_text(
        "// GENERATED by training/export_firmware.py - do not edit.\n"
        '#include "model_registry.h"\n\n'
        f"{externs}\n\nconst ModelEntry kModels[] = {{\n{table}\n}};\n"
        f"const int kModelCount = {len(entries)};\n")

    # Own recordings the deployed models did not train on.
    split_path = JSONL_PATH.parent / "own_test_split.json"
    held_out = json.loads(split_path.read_text())["held_out"] if split_path.exists() else []
    if not all(r.get("own_in_training", True) for r in chosen):
        held_out = []
    listing = "\n".join(f'    "{f}",' for f in held_out) or '    "",'
    (MODELS_OUT / "own_test_split.cpp").write_text(
        "// GENERATED by training/export_firmware.py - do not edit.\n"
        "// Own recordings (<class>/<file>) held out from training the deployed models.\n"
        '#include "model_registry.h"\n\n'
        f"const char* const kOwnHeldOut[] = {{\n{listing}\n}};\n"
        f"const int kOwnHeldOutCount = {len(held_out)};\n")
    print(f"{len(held_out)} held-out own recordings listed in models/own_test_split.cpp")
    print(f"axis map {axis_map}; wrote {SETTINGS_PATH.relative_to(gd.REPO_ROOT)} and "
          f"{len(entries)} model(s) to {MODELS_OUT.relative_to(gd.REPO_ROOT)}/")


if __name__ == "__main__":
    main()
