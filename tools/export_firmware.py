"""Export the deployed model and everything the Pico firmware needs.

    python tools/export_firmware.py        (from hw2/, after running hw2.ipynb)

Writes:
  firmware/lib/model/gesture_model_data.cpp  int8 model with uint8 input/output (as in Lab 2.4)
  firmware/src/preprocessing_settings.hpp    rotation, filter coefficients, mean/std, input quantization
  firmware/lib/model/own_gestures.cpp        the 20 own recordings, for the on-device test
  firmware/own_data_reference.txt            what the PC predicts for them, to compare with the Pico

The firmware repeats src/preprocessor.py step by step, so the constants here
come straight from the same functions.
"""

import sys
from pathlib import Path

import numpy as np
import tensorflow as tf
from scipy.signal import butter, sosfilt_zi

HW2_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HW2_DIR / "src"))
from preprocessor import (load_prepared_dataset, load_csv, preprocess_recording,  # noqa: E402
                          normalize, SAMPLING_RATE_HZ, COUNTS_PER_G)

FW = HW2_DIR / "firmware"
MODEL_H5 = HW2_DIR / "models" / "own_gap_lr1e-2.h5"
RECORD_LEN = 4200          # 2.1 s at 2000 Hz, what the firmware records
TARGET_LEN = 128
CUTOFF_HZ = 20.0
# Same as ROTATION in hw2.ipynb: own (board upright) -> shared frame.
ROTATION = np.array([[0, 0, 1], [0, 1, 0], [-1, 0, 0]], dtype=float)


def c_float(v):
    s = f"{float(v):.9g}"
    if "." not in s and "e" not in s:
        s += ".0"            # "0f" is not a valid C++ literal, "0.0f" is
    return s + "f"


def c_floats(values):
    return ", ".join(c_float(v) for v in np.ravel(values))


def c_sos(name, sos):
    rows = ",\n    ".join("{" + c_floats(r) + "}" for r in sos)
    return f"constexpr float {name}[{len(sos)}][6] = {{\n    {rows}}};\n"


def c_zi(name, zi):
    rows = ", ".join("{" + c_floats(r) + "}" for r in zi)
    return f"constexpr float {name}[{len(zi)}][2] = {{{rows}}};\n"


def to_uint8_tflite(model, X_train):
    def representative_data():
        for x in X_train:
            yield [x[np.newaxis, ..., np.newaxis].astype(np.float32)]
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = representative_data
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.uint8
    conv.inference_output_type = tf.uint8
    return conv.convert()


def main():
    dataset = load_prepared_dataset(HW2_DIR / "data" / "shared_dataset.npz")
    classes = list(dataset["class_names"])
    X_train, _ = dataset["train"]

    # 1. Model
    model = tf.keras.models.load_model(MODEL_H5, compile=False)
    tflite_model = to_uint8_tflite(model, X_train)
    interpreter = tf.lite.Interpreter(model_content=tflite_model)
    interpreter.allocate_tensors()
    inp = interpreter.get_input_details()[0]
    out = interpreter.get_output_details()[0]
    scale, zero_point = inp["quantization"]
    ops = sorted({o["op_name"] for o in interpreter._get_ops_details()})

    data = ", ".join(f"0x{b:02x}" for b in tflite_model)
    (FW / "lib" / "model" / "gesture_model_data.cpp").write_text(
        "// Generated by tools/export_firmware.py from models/own_gap_lr1e-2.h5\n"
        f"// int8 weights, uint8 input/output. Ops: {', '.join(ops)}\n"
        '#include "gesture_model_data.h"\n\n'
        f"alignas(8) const unsigned char gesture_model_data[] = {{{data}}};\n"
        f"const int gesture_model_data_len = {len(tflite_model)};\n")

    # 2. Preprocessing constants (same calls as src/preprocessor.py)
    sos1 = butter(4, CUTOFF_HZ, btype="lowpass", fs=SAMPLING_RATE_HZ, output="sos")
    fs2 = RECORD_LEN - 1                       # resample_gesture: samples per unit time
    sos2 = butter(4, 0.4 * (TARGET_LEN - 1), btype="lowpass", fs=fs2, output="sos")
    settings = f"""// Generated by tools/export_firmware.py. Do not edit by hand.
#ifndef PREPROCESSING_SETTINGS_HPP
#define PREPROCESSING_SETTINGS_HPP

#include <cstdint>

constexpr int kNumAxes = 3;
constexpr int kRecordLength = {RECORD_LEN};   // samples per axis: 2.1 s at {SAMPLING_RATE_HZ:.0f} Hz
constexpr int kTargetLength = {TARGET_LEN};    // model input length
constexpr float kCountsPerG = {COUNTS_PER_G:.1f}f;

// Own board orientation -> orientation of the training data: g_shared = R * g_own.
constexpr float kRotation[3][3] = {{
    {{{c_floats(ROTATION[0])}}}, {{{c_floats(ROTATION[1])}}}, {{{c_floats(ROTATION[2])}}}}};

// Step 1: 4th-order Butterworth low-pass, {CUTOFF_HZ:.0f} Hz at {SAMPLING_RATE_HZ:.0f} Hz.
// Rows are second-order sections (b0 b1 b2 a0 a1 a2). The filter state starts
// at zi * first sample, like scipy's sosfilt with sosfilt_zi.
{c_sos("kLowpassSos", sos1)}{c_zi("kLowpassZi", sosfilt_zi(sos1))}
// Step 2: anti-alias low-pass before resampling {RECORD_LEN} -> {TARGET_LEN} samples.
{c_sos("kResampleSos", sos2)}{c_zi("kResampleZi", sosfilt_zi(sos2))}
// Step 3: normalisation with the training-set statistics (in g).
constexpr float kAxisMean[kNumAxes] = {{{c_floats(dataset["mean"])}}};
constexpr float kAxisStd[kNumAxes] = {{{c_floats(dataset["std"])}}};

// Step 4: uint8 input quantization of the model: q = round(x / scale) + zero_point.
constexpr float kInputScale = {scale:.9g}f;
constexpr int32_t kInputZeroPoint = {zero_point};

#endif  // PREPROCESSING_SETTINGS_HPP
"""
    (FW / "src" / "preprocessing_settings.hpp").write_text(settings)

    # 3. Own recordings + PC reference predictions
    rows, labels, names, ref = [], [], [], []
    for label, cls in enumerate(classes):
        for path in sorted((HW2_DIR / "data" / "own" / cls).glob("*.txt")):
            raw = load_csv(path)[:RECORD_LEN].astype(np.int16)
            x = preprocess_recording(raw, sample_rate_hz=SAMPLING_RATE_HZ,
                                     target_length=TARGET_LEN, rotation=ROTATION)
            x = normalize(x[np.newaxis], dataset)[..., np.newaxis]
            q = np.clip(np.round(x / scale) + zero_point, 0, 255).astype(np.uint8)
            interpreter.set_tensor(inp["index"], q)
            interpreter.invoke()
            pred = int(interpreter.get_tensor(out["index"])[0].argmax())
            rows.append(raw)
            labels.append(label)
            names.append(path.name)
            ref.append(f"{path.name} true={cls} pred={classes[pred]} input_sum={int(q.sum())}")

    body = ",\n".join("  {" + ", ".join(f"{{{a},{b},{c}}}" for a, b, c in r) + "}" for r in rows)
    (FW / "lib" / "model" / "own_gestures.cpp").write_text(
        "// Generated by tools/export_firmware.py: own recordings (raw counts) for own_data_test.\n"
        '#include "own_gestures.h"\n\n'
        f"const int own_gesture_count = {len(rows)};\n"
        f"const uint8_t own_gesture_labels[] = {{{', '.join(map(str, labels))}}};\n"
        "const char* const own_gesture_names[] = {"
        + ", ".join(f'"{n}"' for n in names) + "};\n"
        f"const int16_t own_gestures[][{RECORD_LEN}][3] = {{\n{body}\n}};\n")

    correct = sum(f"true={c} pred={c} " in r for r, c in zip(ref, [classes[i] for i in labels]))
    ref.append(f"PC accuracy: {correct}/{len(rows)}")
    (FW / "own_data_reference.txt").write_text("\n".join(ref) + "\n")

    print(f"model: {len(tflite_model)} bytes, ops {ops}")
    print(f"input scale {scale:.6g}, zero point {zero_point}")
    print("\n".join(ref))


if __name__ == "__main__":
    main()
